import { chromium } from 'playwright'
const b = await chromium.launch()
const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, hasTouch: true, isMobile: true })
const p = await ctx.newPage()
const out = []
await p.goto('http://localhost:4544/traningsplaneringen/')
await p.waitForTimeout(800)
await p.getByRole('button', { name: 'Planera pass' }).click()
await p.waitForTimeout(400)
await p.getByRole('option', { name: '7–9 år' }).click()
await p.getByRole('button', { name: 'Nästa' }).click()
await p.getByRole('option', { name: 'Trampett' }).click()
await p.getByRole('button', { name: 'Nästa' }).click()
await p.waitForTimeout(300)
out.push('wizard step3 options: ' + JSON.stringify(await p.getByRole('option').allInnerTexts()))
out.push('wizard step3 texts: ' + JSON.stringify(await p.locator('.home-wizard p').allInnerTexts()))
await p.screenshot({ path: 's45-wizard-step3.png' })
await p.getByRole('option', { name: 'Blå hall' }).click()
await p.getByRole('button', { name: 'Skapa pass' }).click()
await p.waitForTimeout(900)
await p.getByRole('button', { name: 'Fler saker med passet' }).click()
await p.locator('.more-menu-panel').getByRole('button', { name: 'Hallöversikt' }).click()
await p.waitForTimeout(900)
out.push('layout options: ' + JSON.stringify(await p.locator('#hall-layout-select option').allInnerTexts()))
out.push('hall-below texts: ' + JSON.stringify(await p.locator('.hall-below p, .hall-below button').allInnerTexts()))
out.push('tray texts: ' + JSON.stringify(await p.locator('.hall-tray p').allInnerTexts()))
const r = await p.evaluate(() => { const q = s => { const e = document.querySelector(s); if (!e) return null; const r = e.getBoundingClientRect(); return [Math.round(r.top + scrollY), Math.round(r.bottom + scrollY)] }; return { presetRow: q('.hall-preset-row'), canvas: q('.hall-canvas'), below: q('.hall-below'), docH: document.documentElement.scrollHeight } })
out.push('measure: ' + JSON.stringify(r))
await p.screenshot({ path: 's45-hall-bla-390.png', fullPage: true })
// Golvklart
await p.getByRole('button', { name: 'Golvklart' }).first().click()
await p.waitForTimeout(600)
out.push('golvklart meta: ' + JSON.stringify(await p.locator('.hall-session-meta').allInnerTexts()))
await p.screenshot({ path: 's45-golvklart-390.png' })
// Home -> Rensa passet
await p.goto('http://localhost:4544/traningsplaneringen/')
await p.waitForTimeout(800)
await p.getByRole('button', { name: 'Rensa passet' }).click()
await p.waitForTimeout(300)
const m = await p.evaluate(() => { const e = document.querySelector('.replace-draft-backdrop .modal'); const r = e.getBoundingClientRect(); const bs = [...e.querySelectorAll('button')].map(b => { const x = b.getBoundingClientRect(); return [b.innerText, Math.round(x.width), Math.round(x.height), Math.round(x.top)] }); return { top: Math.round(r.top), bottom: Math.round(r.bottom), h: Math.round(r.height), w: Math.round(r.width), buttons: bs, text: e.innerText } })
out.push('rensa dialog: ' + JSON.stringify(m))
await p.screenshot({ path: 's45-rensa-dialog-390.png' })
console.log(out.join('\n'))
await b.close()
