import { chromium } from 'playwright'
const b = await chromium.launch()
const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, hasTouch: true, isMobile: true, permissions: ['clipboard-read','clipboard-write'] })
const p = await ctx.newPage()
await p.goto('http://localhost:4544/traningsplaneringen/')
await p.waitForTimeout(800)
await p.getByRole('button', { name: 'Från mall' }).click()
await p.waitForTimeout(500)
await p.getByRole('button', { name: /Nybörjare/ }).click()
await p.waitForTimeout(800)
await p.getByRole('button', { name: 'Fler saker med passet' }).click()
await p.locator('.more-menu-panel').getByRole('button', { name: 'Exportera / dela' }).click()
await p.waitForTimeout(800)
const btn = p.locator('.export-sheet').getByRole('button', { name: 'Kopiera länk' })
await btn.click()
await p.waitForTimeout(300)
console.log('button after copy:', await p.locator('.export-sheet .export-block').nth(1).locator('button').first().innerText())
console.log('toast count:', await p.locator('.toast').count())
const clip = await p.evaluate(() => navigator.clipboard.readText())
console.log('clip len', clip.length, clip.slice(0, 90))
await p.locator('.export-sheet').screenshot({ path: 'export-sheet-after-copy.png' })
const p2 = await ctx.newPage()
await p2.goto(clip)
await p2.waitForTimeout(1200)
console.log('share view buttons:', await p2.locator('.share-actions button').allInnerTexts())
console.log('banner:', await p2.locator('.share-banner').innerText())
await p2.screenshot({ path: 'share-view-390.png', fullPage: false })
await b.close()
